    classes = list(train_data.class_indices.keys())

    print("\nTesting prediction...")
    test_img = '/content/drive/MyDrive/fruits/fruits/Fruits Classification/test/Apple/Apple (12).png'
    predict_fruit(test_img, model, classes)

